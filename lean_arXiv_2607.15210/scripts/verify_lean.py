#!/usr/bin/env python3
"""Rebuild all current Lean sources and audit every project declaration.

The source manifest and audit are generated from the import graph. Compilation
success is distinct from completion of the paper's theorem statements.
"""
from __future__ import annotations

import argparse
from concurrent.futures import ThreadPoolExecutor, wait, FIRST_COMPLETED
import hashlib
import json
from pathlib import Path
import re
import subprocess
import time

ROOT = Path(__file__).resolve().parents[1]
RECORDS = ROOT / 'verification'
LEAN_ROOT = ROOT / 'lean'
AGGREGATE = 'Checks.AggregateAudit'
IMPORT = re.compile(r'^import\s+([\w.]+)\s*$', re.M)


def source_modules():
    """Every maintained source, including helper and audit modules."""
    return {'.'.join(p.relative_to(LEAN_ROOT).with_suffix('').parts): p
            for p in sorted(LEAN_ROOT.rglob('*.lean'))
            if p != LEAN_ROOT / 'Checks/AggregateAudit.lean'}


def partial_progress_index(modules):
    """Record every local dependency of each strong-convergence source."""
    rows = []
    for name in sorted(m for m in modules if m.startswith('StrongConvergence.')):
        seen = set()
        def visit(module):
            if module in seen:
                return
            seen.add(module)
            for dep in IMPORT.findall(modules[module].read_text()):
                if dep in modules:
                    visit(dep)
        visit(name)
        rows.append({'module': name, 'path': str(modules[name].relative_to(ROOT)),
                     'local_import_closure': [
                         {'module': m, 'path': str(modules[m].relative_to(ROOT))}
                         for m in sorted(seen)]})
    return json.dumps(rows, indent=2) + '\n'


def import_order(modules):
    ordered, visiting = [], set()
    def visit(name):
        if name in ordered:
            return
        if name in visiting:
            raise RuntimeError('Import cycle: ' + name)
        visiting.add(name)
        for dep in IMPORT.findall(modules[name].read_text()):
            if dep in modules:
                visit(dep)
        visiting.remove(name)
        ordered.append(name)
    for name in sorted(modules):
        visit(name)
    return ordered


def write_aggregate_audit(modules):
    # Import every source, including modules containing definitions only.
    names = sorted(modules)
    source = '\n'.join('import ' + name for name in names)
    source += '''
import Lean.Util.CollectAxioms

set_option maxHeartbeats 0

open Lean in
run_elab do
  let projectModules : Array Name := #[MODULE_NAMES]
  let allowed : Array Name := #[`propext, `Classical.choice, `Quot.sound]
  let env ← getEnv
  let mut names : Array Name := #[]
  let mut logicalAxioms : Array Name := #[]
  let mut theorems : Nat := 0
  for (name, ci) in env.constants.toList do
    if let some mi := env.getModuleIdxFor? name then
      if projectModules.contains env.allImportedModuleNames[mi.toNat]! then
        if ci.isTheorem then
          theorems := theorems + 1
        if let .axiomInfo v := ci then
          if !v.isUnsafe then
            logicalAxioms := logicalAxioms.push name
        if !ci.isUnsafe then
          names := names.push name
  names := names.qsort Name.lt
  for name in names do
    logInfo m!"AUDIT_DECLARATION {name}"
  let action : CollectAxioms.M Unit := names.forM CollectAxioms.collect
  let (_, state) := (action.run env).run {}
  let axioms := state.axioms.qsort Name.lt
  logInfo m!"TRANSITIVE AXIOMS: {axioms.toList}"
  logInfo m!"PROJECT LOGICAL AXIOMS: {logicalAxioms.toList}"
  logInfo m!"AUDITED DECLARATIONS: {names.size}"
  logInfo m!"AUDITED THEOREMS: {theorems}"
  if !logicalAxioms.isEmpty || axioms.any (fun a => !allowed.contains a) then
    throwError "Aggregate axiom audit failed"
  logInfo "Aggregate audit passed"
'''.replace('MODULE_NAMES', ', '.join('`' + name for name in names))
    (LEAN_ROOT / 'Checks/AggregateAudit.lean').write_text(source)


def write_all_proofs(modules):
    excluded = {'AllProofs', 'Checks.ResultChecks', 'Checks.UnprovedTargets', AGGREGATE}
    names = sorted(name for name in modules
                   if name not in excluded and not name.endswith('Audit'))
    source = '\n'.join('import ' + name for name in names)
    source += '''

/-!
# All checked proof sources

Generated by `scripts/verify_lean.py`. The numbered guides in `results/`
identify the exact paper statements, hypotheses, and proof obligations.
Importing a conditional theorem does not discharge its hypotheses.
-/
'''
    (LEAN_ROOT / 'AllProofs.lean').write_text(source)


def verify(direct=False, jobs=2):
    RECORDS.mkdir(exist_ok=True)
    logs = RECORDS / 'lean_logs'
    logs.mkdir(exist_ok=True)
    status_path = RECORDS / 'verification_status.json'
    # Invalidate the previous success before running a new source snapshot.
    status_path.write_text(json.dumps({'status': 'running'}) + '\n')
    modules = source_modules()
    write_all_proofs(modules)
    modules['AllProofs'] = LEAN_ROOT / 'AllProofs.lean'
    ordered = import_order(modules)
    write_aggregate_audit(modules)
    modules[AGGREGATE] = LEAN_ROOT / 'Checks/AggregateAudit.lean'
    ordered.append(AGGREGATE)
    (ROOT / 'partial_progress/source_index.json').write_text(partial_progress_index(modules))
    prefix = ['lean'] if direct else ['lake', 'env', 'lean']
    # Resolve a changed Lake configuration once before independent workers
    # enter `lake env`; simultaneous reconfiguration requires an exclusive lock.
    subprocess.run(prefix + ['--version'], cwd=ROOT, check=True,
                   stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    hashes = {name: hashlib.sha256(path.read_bytes()).hexdigest()
              for name, path in modules.items()}
    dependencies = {name: set(IMPORT.findall(path.read_text())) & modules.keys()
                    for name, path in modules.items()}

    def compile_one(name):
        path = modules[name]
        out = ROOT / '.lake/build/lib/lean' / Path(*name.split('.')).with_suffix('.olean')
        out.parent.mkdir(parents=True, exist_ok=True)
        log = logs / (name + '.log')
        start = time.monotonic()
        with log.open('w') as handle:
            run = subprocess.run(prefix + ['--root=lean', '-o', str(out), str(path.relative_to(ROOT))],
                                 cwd=ROOT, stdout=handle, stderr=subprocess.STDOUT)
        text = log.read_text()
        if run.returncode or 'sorryAx' in text or "declaration uses 'sorry'" in text:
            raise RuntimeError(f'{name} failed ({run.returncode}):\n{text}')
        if hashlib.sha256(path.read_bytes()).hexdigest() != hashes[name]:
            raise RuntimeError('Source changed during compilation: ' + name)
        return {'module': name, 'path': str(path.relative_to(ROOT)),
                'sha256': hashes[name], 'imports': IMPORT.findall(path.read_text()),
                'exit_code': 0, 'seconds': round(time.monotonic() - start, 3)}

    # Only independent ready modules run together. Every local dependency is
    # rebuilt before its importer; each source still receives its own kernel check.
    pending, completed, running = list(ordered), {}, {}
    try:
        with ThreadPoolExecutor(max_workers=max(1, jobs)) as pool:
            while pending or running:
                ready = [name for name in pending if dependencies[name] <= completed.keys()]
                for name in ready[:max(1, jobs)-len(running)]:
                    pending.remove(name)
                    running[pool.submit(compile_one, name)] = name
                if not running:
                    raise RuntimeError('Unresolved import dependencies: ' + ', '.join(pending))
                done, _ = wait(running, return_when=FIRST_COMPLETED)
                for future in done:
                    name = running.pop(future)
                    completed[name] = future.result()
                    print('Checked', name, flush=True)
    except Exception as exc:
        status_path.write_text(json.dumps({'status': 'failed', 'error': str(exc)}) + '\n')
        raise
    records = [completed[name] for name in ordered]
    audit = (logs / (AGGREGATE + '.log')).read_text()
    if 'Aggregate audit passed' not in audit:
        raise RuntimeError('Missing successful aggregate audit')
    count = int(re.search(r'AUDITED DECLARATIONS: (\d+)', audit)[1])
    theorem_count = int(re.search(r'AUDITED THEOREMS: (\d+)', audit)[1])
    status = {'status': 'pass', 'lean_version': '4.19.0',
              'mathlib_commit': 'c44e0c8ee63ca166450922a373c7409c5d26b00b',
              'compiled_modules': len(records), 'audited_declarations': count,
              'audited_theorem_declarations_including_generated': theorem_count,
              'allowed_axioms': ['propext', 'Classical.choice', 'Quot.sound'],
              'scope': 'All indexed source declarations checked; consult results/RESULTS.json for paper coverage.',
              'modules': records}
    subprocess.run(['python3', 'scripts/verify_entropy_statements.py'], cwd=ROOT, check=True)
    for record in records:
        if hashlib.sha256((ROOT / record['path']).read_bytes()).hexdigest() != record['sha256']:
            raise RuntimeError('Source changed during verification: ' + record['module'])
    status_path.write_text(json.dumps(status, indent=2) + '\n')
    (RECORDS / 'source_manifest.json').write_text(json.dumps(records, indent=2) + '\n')
    (RECORDS / 'axiom_audit.log').write_text(audit)
    return status


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--direct', action='store_true')
    parser.add_argument('--jobs', type=int, default=2, help='Independent Lean processes (default: 2)')
    args = parser.parse_args()
    result = verify(args.direct, args.jobs)
    print('Aggregate audit passed:', result['compiled_modules'], 'modules,',
          result['audited_declarations'], 'declarations.')
